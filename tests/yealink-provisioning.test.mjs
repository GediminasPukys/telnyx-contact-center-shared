const phone = { id: "test-phone", mac: "001565000001", vendor: "yealink", model: "T22P",
  sip_username: "credential", sip_password: "sip-secret", admin_password: "private-admin",
  extension: "1004", settings: {} };
const keys = generateKeyPairSync("rsa", { modulusLength: 2048 });
const jwk = keys.publicKey.export({ format: "jwk" });
const n = Buffer.from(jwk.n, "base64url").toString("hex"), e = Buffer.from(jwk.e, "base64url").toString("hex");
const html = states => `<td id="tdFirmware">7.73.0.50</td><td id="tdMACAddress">001565000001</td><tbody id="StatusAccountStatus">${states.map(s => `<script>T("${s}")</script>`).join("")}</tbody>`;

test("legacy servlet encryption matches the firmware envelope without plaintext secrets", () => {
  const plaintext = "rand=0.5;AutoProvisionPassword=test-secret;sessionid=12345678;";
  const result = encryptYealinkFields(n,e,plaintext);
  const decryptKey = value => {
    const padded = privateDecrypt({ key: keys.privateKey, padding: constants.RSA_NO_PADDING }, Buffer.from(value,"hex"));
    assert.equal(padded[1],2);
    return Buffer.from(padded.subarray(padded.indexOf(0,2)+1).toString(),"hex");
  };
  const decipher = createDecipheriv("aes-128-cbc",decryptKey(result.key),decryptKey(result.iv));
  decipher.setAutoPadding(false);
  const decoded = Buffer.concat([decipher.update(Buffer.from(result.data,"base64")),decipher.final()]).toString().replace(/\0+$/,"");
  assert.equal(decoded,`MD5=${createHash("md5").update(plaintext).digest("hex")};${plaintext}`);
  assert.ok(!JSON.stringify(result).includes("test-secret"));
  assert.throws(() => encryptYealinkFields("bad",e,plaintext),/unsupported_device_response/);
});

test("T22P bootstrap and full config use legacy keys and distinct credentials", () => {
  process.env.HARDPHONE_PROVISIONING_SECRET ||= "unit-test-secret-with-at-least-32-characters";
  const enrollment={generation:"test",base_url:"https://cc.example.com"};
  const bootstrap=yealinkBootstrapConfig(phone,enrollment);
  assert.match(bootstrap,/^auto_provision.server.url = https:\/\/cc.example.com\/api\/provisioning\/$/m);
  assert.doesNotMatch(bootstrap,/static\.|sip-secret|private-admin/);
  const config=yealinkPhoneConfig(phone,{baseUrl:enrollment.base_url,credential:{username:phone.mac,password:"device-only"}});
  assert.match(config,/^account.1.label = 1004$/m);
  assert.match(config,/^account.1.user_name = credential$/m);
  assert.match(config,/^security.user_password = admin:private-admin$/m);
  assert.match(config,/^auto_provision.server.password = device-only$/m);
  assert.doesNotMatch(config,/^static\./m);
});

test("unknown/missing account status is not idle or registered", () => {
  assert.equal(parseYealinkStatus("").allAccountsDisabled,false);
  assert.equal(parseYealinkStatus(html(["Disabled","Disabled","Disabled"])).allAccountsDisabled,true);
  assert.equal(parseYealinkStatus(html(["Registered","Disabled","Disabled"])).allAccountsDisabled,false);
  assert.equal(parseYealinkStatus(html(["Registered","Disabled","Disabled"])).registered,true);
});

test("V73 forms include the per-page CSRF token generated by its UI", () => {
  const html = '<script>UpdateToken("1589993805");</script><form name="formInput"><input name="AutoProvisionUser" value="existing"></form>';
  const form = yealinkProvisioningForm(html);
  assert.equal(form.get("token"),"1589993805");
  assert.equal(form.get("AutoProvisionUser"),"existing");
  assert.throws(() => yealinkProvisioningForm(html.replace('UpdateToken("1589993805")',"")),/unsupported_device_form/);
});

test("legacy authentication requires the exact success redirect and validates device identity", async () => {
  const request=async (_phone,path,options={}) => {
    if(path.endsWith("getsessionid"))return{status:200,raw:`${n},${e},12345678`,headers:{}};
    if(path.endsWith("q=login")) {
      assert.equal(options.headers.Cookie,"JSESSIONID=12345678");
      assert.ok(!options.body.includes("private-admin"));
      return{status:302,raw:"",headers:{location:"/servlet?p=status&q=load "}};
    }
    return{status:200,headers:{},raw:html(["Disabled","Disabled","Disabled"])};
  };
  const result=await inspectYealink(phone,null,{request});
  assert.equal(result.model,"T22P"); assert.equal(result.allAccountsDisabled,true);
  await assert.rejects(inspectYealink({...phone,mac:"000000000001"},null,{request}),/device_mac_mismatch/);
  await assert.rejects(yealinkLegacySession(phone,{request:async(p,path,o)=>path.endsWith("q=login")?{status:200,raw:"Invalid password",headers:{}}:request(p,path,o)}),/auth_failed/);
});

test("legacy form saves accept only the declared local redirect, including V73 trailing spaces", async () => {
  let location = "/servlet?p=settings-autop&q=load ";
  let calls = 0;
  const request = async (_phone,path,options={}) => {
    calls++;
    assert.equal(options.expectedRedirect,undefined);
    if(path.endsWith("getsessionid"))return {status:200,raw:`${n},${e},12345678`,headers:{}};
    if(path.endsWith("q=login"))return {status:302,raw:"",headers:{location:"/servlet?p=status&q=load"}};
    return {status:302,raw:"",headers:{location}};
  };
  const session = await yealinkLegacySession(phone,{request});
  const send = () => session.send("/servlet?p=settings-autop&q=write",{
    method:"POST",expectedRedirect:"/servlet?p=settings-autop&q=load",
  });
  await send();
  assert.equal(calls,3,"must not follow the redirect with device credentials");
  location="https://untrusted.example/servlet?p=settings-autop&q=load";
  await assert.rejects(send(),/unsupported_device_response/);
  location="/servlet?p=login&q=load";
  await assert.rejects(send(),/auth_failed/);
  location="/servlet?p=settings-autop&q=load";
  await assert.rejects(session.send("/save"),/unsupported_device_response/);
});

test("Action URI does not acknowledge login pages or a handset approval prompt", async () => {
  assert.equal(normalizeYealinkActionResult({status:200,raw:""}).ok,true);
  for(const status of [200,412]) {
    assert.equal(normalizeYealinkActionResult({status,raw:"<h1>remote control forbidden</h1>"}).reason,"remote_control_approval_required");
  }
  assert.equal(normalizeYealinkActionResult({status:200,raw:'<html><form action="/servlet?p=login">'}).ok,false);
  assert.equal(normalizeYealinkActionResult({status:302,raw:""}).ok,false);
  assert.equal(normalizeYealinkActionResult({status:401,raw:""}).reason,"auth_failed");
  for (const action of ["answer", "hangup", "hold", "resume"]) {
    for (const callRef of ["101;Reboot", "101&key=Reboot", "101%3A", ""]) {
      assert.deepEqual(await yealinkDriver[action](phone,{callRef}),{ok:false,reason:"invalid_call_reference"});
    }
  }
});
